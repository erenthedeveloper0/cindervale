/**
 * ANSI palette. Hues map one-to-one onto the theme: red → diagnostics red,
 * green → sage, yellow → amber, blue → blue, magenta → plum, cyan →
 * eucalyptus. Light-theme colors clear 4.5:1 on the panel so VS Code's
 * minimum-contrast correction never has to repaint them.
 */
function ansi(p) {
  const { source: src, state: st } = p;
  const hues = {
    Red: st.error,
    Green: src.sage,
    Yellow: src.amber,
    Blue: src.blue,
    Magenta: src.plum,
    Cyan: src.eucalyptus,
  };
  const colors = {};
  if (p.type === 'dark') {
    colors['terminal.ansiBlack'] = src.border;
    colors['terminal.ansiBrightBlack'] = mix(src.disabled, src.secondary, 0.5);
    for (const [name, tone] of Object.entries(hues)) {
      colors[`terminal.ansi${name}`] = tone;
      colors[`terminal.ansiBright${name}`] = adjust(tone, { l: 0.06, c: 1.08 });
    }
    colors['terminal.ansiWhite'] = mix(src.secondary, src.foreground, 0.5);
    colors['terminal.ansiBrightWhite'] = src.foreground;
  } else {
    colors['terminal.ansiBlack'] = src.foreground;
    colors['terminal.ansiBrightBlack'] = src.secondary;
    for (const [name, tone] of Object.entries(hues)) {
      colors[`terminal.ansi${name}`] = ink(tone, src.panel, 5.4);
      colors[`terminal.ansiBright${name}`] = ink(adjust(tone, { c: 1.12 }), src.panel, 4.6);
    }
    colors['terminal.ansiWhite'] = mix(src.secondary, src.disabled, 0.5);
    colors['terminal.ansiBrightWhite'] = mix(src.disabled, src.border, 0.35);
  }
  return colors;
}
